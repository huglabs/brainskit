def render_page(operation: PageOperation) -> str:
    metadata = page_metadata(operation)
    lines = [FRONTMATTER_BOUNDARY]
    for key, value in metadata.items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.extend(f"  - {json.dumps(item, ensure_ascii=False)}" for item in value)
        else:
            lines.append(f"{key}: {json.dumps(value, ensure_ascii=False)}")
    lines.extend([FRONTMATTER_BOUNDARY, "", f"# {operation.title}", "", operation.body, ""])
    return "\n".join(lines)


def page_metadata(operation: PageOperation) -> dict[str, Any]:
    metadata: dict[str, Any] = {
        "id": operation.page_id,
        "type": operation.kind.value,
        "title": operation.title,
        "aliases": list(operation.aliases),
        "sources": list(operation.source_hashes),
    }
    # Emitted only when the page has one. Writing an empty list on every page
    # would rewrite the frontmatter of every existing page in a vault the first
    # time it is touched, for a field that says nothing.
    if operation.code_sources:
        metadata["code_sources"] = [entry.to_dict() for entry in operation.code_sources]
    metadata["updated_at"] = utc_now()
    metadata.update(operation.metadata)
    return metadata


def parse_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    if not text.startswith("---\n"):
        return {}, text
    boundary = text.find("\n---\n", 4)
    if boundary < 0:
        return {}, text
    raw = text[4:boundary].splitlines()
    body = text[boundary + 5 :]
    metadata: dict[str, Any] = {}
    current_list: str | None = None
    for line in raw:
        if line.startswith("  - ") and current_list:
            value = line[4:].strip()
            metadata[current_list].append(_parse_yaml_scalar(value))
            continue
        current_list = None
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        key, value = key.strip(), value.strip()
        if not value:
            metadata[key] = []
            current_list = key
        else:
            metadata[key] = _parse_yaml_scalar(value)
    return metadata, body


def _parse_yaml_scalar(value: str) -> Any:
    try:
        return json.loads(value)
    except json.JSONDecodeError:
        return value


def _focused_excerpt(content: str, query: str, limit: int) -> str:
    compact = re.sub(r"\s+", " ", content).strip()
    if len(compact) <= limit:
        return compact
    tokens = [token.lower() for token in re.findall(r"\w+", query)]
    lowered = compact.lower()
    positions = [lowered.find(token) for token in tokens if lowered.find(token) >= 0]
    center = min(positions) if positions else 0
    start = max(0, center - limit // 4)
    end = min(len(compact), start + limit)
    prefix = "…" if start else ""
    suffix = "…" if end < len(compact) else ""
    return prefix + compact[start:end] + suffix


def _normalize_identity(value: str) -> str:
    normalized = "".join(
        character
        for character in unicodedata.normalize("NFKD", value.casefold())
        if not unicodedata.combining(character)
    )
    return " ".join(re.findall(r"[a-z0-9]+", normalized))


def _normalized_tokens(value: str) -> list[str]:
    # Both citation forms are stripped: a 64-character hash is not vocabulary,
    # and leaving it in would make two pages citing the same file look related
    # for a reason that has nothing to do with what they say.
    without_citations = CODE_CITATION_RE.sub("", CITATION_RE.sub("", value))
    normalized = "".join(
        character
        for character in unicodedata.normalize(
            "NFKD", without_citations.casefold()
        )
        if not unicodedata.combining(character)
    )
    return [
        token
        for token in re.findall(r"[a-z0-9]{2,}", normalized)
        if not token.isdigit()
    ]


def _content_tokens(value: str) -> set[str]:
    return set(_normalized_tokens(value))


def _is_salient_term(token: str) -> bool:
    return len(token) >= 3 and token not in _STOPWORDS


def _stable_payload_hash(value: dict[str, Any]) -> str:
    return hashlib.sha256(
        json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
        ).encode("utf-8")
    ).hexdigest()
